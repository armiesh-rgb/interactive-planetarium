// Создаём записи зодиакальных созвездий.
Object.keys(zodiacLines).forEach(function(name) {
    const stars = zodiacStars.filter(function(star) {
        return star.constellation === name;
    });

    if (!stars.length) return;

    const ra = stars.reduce(function(sum, star) {
        return sum + star.ra;
    }, 0) / stars.length;

    const dec = stars.reduce(function(sum, star) {
        return sum + star.dec;
    }, 0) / stars.length;

    constellationData[name] = {
        name: name,
        ra: ra,
        dec: dec,
        stars: stars.map(function(star) {
            return star.name;
        }),
        lines: zodiacLines[name]
    };
});
